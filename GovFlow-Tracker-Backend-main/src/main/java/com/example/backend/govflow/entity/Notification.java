package com.example.backend.govflow.entity;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;

import java.time.Instant;

/**
 * Represents a notification sent to a user within the system.
 * Each notification is linked to a user and contains a title, a message,
 * and a status indicating whether it has been read.
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Entity
@Table(name = "notifications")
public class Notification {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * The user who receives this notification. This creates a many-to-one
     * relationship, as one user can have many notifications.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    /**
     * The title of the notification. It is a required field.
     */
    @Column(nullable = false, length = 255)
    private String title;

    /**
     * The detailed message content of the notification. It is stored as TEXT
     * to allow for longer messages and is a required field.
     */
    @Column(columnDefinition = "TEXT", nullable = false)
    private String message;

    /**
     * A boolean flag to indicate if the notification has been read by the user.
     * Defaults to 'false' in the database schema.
     */
    @Column(name = "is_read", nullable = false)
    private boolean isRead = false;

    /**
     * The timestamp when the notification was created. This is automatically
     * generated by the database and is not updatable.
     */
    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;
}